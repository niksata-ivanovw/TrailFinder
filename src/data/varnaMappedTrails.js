const osmRoute = (relationId) => `https://www.openstreetmap.org/relation/${relationId}`;

function makeTrail({
  id,
  name,
  location,
  description,
  difficulty,
  surfaceType,
  distanceMiles,
  imageUrl,
  relationId,
  coordinates,
}) {
  const start = coordinates[0];
  const end = coordinates[coordinates.length - 1];

  return {
    id,
    name,
    location,
    description,
    difficulty,
    surfaceType,
    distanceMiles,
    elevationGainFt: null,
    imageUrl,
    coordinates: coordinates.map(([latitude, longitude]) => ({ latitude, longitude })),
    waypoints: [
      { type: 'trailhead', title: 'Route start', latitude: start[0], longitude: start[1] },
      { type: 'trailhead', title: 'Route end', latitude: end[0], longitude: end[1] },
    ],
    source: {
      name: 'OpenStreetMap',
      relationId,
      url: osmRoute(relationId),
      license: 'ODbL',
    },
  };
}

